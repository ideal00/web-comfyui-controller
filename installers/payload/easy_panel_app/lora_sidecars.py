def read_safetensors_metadata(path: Path, max_header_bytes: int = 64 * 1024 * 1024) -> dict[str, str]:
    """Read only the safetensors JSON metadata header."""
    file = Path(path)
    with file.open("rb") as handle:
        size_raw = handle.read(8)
        if len(size_raw) != 8:
            raise ValueError("文件太短，不是有效的 safetensors。")
        header_size = int.from_bytes(size_raw, "little")
        if not 2 <= header_size <= max_header_bytes:
            raise ValueError(f"safetensors 头部大小异常：{header_size} bytes。")
        header = json.loads(handle.read(header_size).decode("utf-8"))
    metadata = header.get("__metadata__", {}) if isinstance(header, dict) else {}
    return {str(key): str(value) for key, value in metadata.items()} if isinstance(metadata, dict) else {}


def _json_object(value: str):
    try:
        return json.loads(str(value or ""))
    except (TypeError, json.JSONDecodeError):
        return None


def _metadata_tag_counter(metadata: dict[str, str]) -> Counter:
    counter: Counter = Counter()
    parsed = _json_object(metadata.get("ss_tag_frequency", ""))
    if isinstance(parsed, dict):
        for value in parsed.values():
            if isinstance(value, dict):
                for tag, count in value.items():
                    try:
                        counter[str(tag)] += int(count)
                    except (TypeError, ValueError):
                        continue
    for key in ("modelspec.tags", "modelspec.trigger_phrase", "trigger_words", "activation text"):
        raw = metadata.get(key, "")
        for tag in split_prompt_tags(raw):
            counter[tag] += max(1, counter.total() // 100)
    return counter


def infer_base_model(metadata: dict[str, str], path: Path | None = None) -> str:
    haystack = " ".join(
        metadata.get(key, "") for key in (
            "ss_base_model_version", "ss_sd_model_name", "modelspec.architecture",
            "modelspec.implementation", "modelspec.title", "ss_network_module",
        )
    )
    if path:
        haystack += " " + str(path)
    low = haystack.casefold()
    if "anima" in low:
        return "Anima"
    if any(token in low for token in ("illustrious", "noobai", "ilxl", "wai")):
        return "Illustrious"
    if "pony" in low:
        return "Pony SDXL"
    if "flux" in low:
        return "FLUX"
    if any(token in low for token in ("sdxl", "stable-diffusion-xl", "sd_xl")):
        return "SDXL"
    if any(token in low for token in ("sd15", "sd 1.5", "stable-diffusion-v1")):
        return "SD 1.5"
    return ""


def sidecar_from_safetensors(path: Path, max_tags: int = 80) -> dict:
    """Build a smart sidecar document from embedded training metadata."""
    file = Path(path)
    metadata = read_safetensors_metadata(file)
    counter = _metadata_tag_counter(metadata)
    ranked: list[str] = []
    for tag, _ in counter.most_common(max_tags * 3):
        normalized = normalize_tag(tag)
        if not normalized or normalized in _QUALITY_TAGS or normalized.startswith("score "):
            continue
        if re.fullmatch(r"(?:rating|source|year)\s+\w+", normalized):
            continue
        ranked.append(tag)
        if len(ranked) >= max_tags:
            break
    sections = classify_tag_list(ranked)
    explicit_trigger = ""
    for key in ("modelspec.trigger_phrase", "trigger_words", "activation text"):
        candidates = split_prompt_tags(metadata.get(key, ""))
        if candidates:
            explicit_trigger = candidates[0]
            break
    trigger = explicit_trigger or next(
        (tag for tag in ranked if is_trigger_or_character(tag) and classify_tag(tag)[0] == "subject"),
        "",
    )
    title = metadata.get("modelspec.title") or metadata.get("ss_output_name") or file.stem
    url = metadata.get("modelspec.url", "")
    outfit = _serialise_outfit("自动提取", {key: sections.get(key, []) for key in NOTE_FIELDS})
    return {
        "schema_version": 2,
        "title": title,
        "base_model": infer_base_model(metadata, file),
        "weight": metadata.get("modelspec.recommended_weight", "0.7"),
        "trigger": trigger,
        "url": url,
        "outfits": [outfit] if len(outfit) > 1 else [],
        "metadata_keys": len(metadata),
        "training_tag_count": len(counter),
    }


def render_sidecar(document: dict, source_name: str = "") -> str:
    lines = [SIDECAR_MARKER, "# 本文件由本地元数据生成；请核对触发词后再正式出图。"]
    lines.extend((
        f"名称：{document.get('title', '')}",
        f"适用底模：{document.get('base_model', '')}",
        f"推荐权重：{document.get('weight', '')}",
        f"触发词：{document.get('trigger', '')}",
        f"来源：{document.get('url', '')}",
    ))
    if source_name:
        lines.append(f"生成器来源：{source_name}")
    for outfit in document.get("outfits", []):
        lines.extend(("", f"[{outfit.get('name', '自动提取')}]"))
        for category in NOTE_FIELDS:
            value = str(outfit.get(category, "") or "").strip()
            if value:
                lines.append(f"{SECTION_LABELS[category]}：{value}")
    lines.append("")
    return "\n".join(lines)


def is_generated_sidecar(path: Path) -> bool:
    try:
        first = Path(path).read_text(encoding="utf-8-sig", errors="replace")[:200]
    except OSError:
        return False
    return SIDECAR_MARKER in first


def read_text_smart(path: Path) -> str:
    """Read common UTF/Chinese/Japanese TXT encodings without mojibake."""
    data = Path(path).read_bytes()
    if not data:
        return ""
    if data.startswith(b"\xef\xbb\xbf"):
        return data.decode("utf-8-sig")
    if data.startswith((b"\xff\xfe", b"\xfe\xff")):
        return data.decode("utf-16")
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        pass
    if data.count(b"\x00") > max(2, len(data) // 20):
        for encoding in ("utf-16-le", "utf-16-be"):
            try:
                return data.decode(encoding)
            except UnicodeDecodeError:
                continue
    legacy: dict[str, str] = {}
    for encoding in ("gb18030", "cp932"):
        try:
            legacy[encoding] = data.decode(encoding)
        except UnicodeDecodeError:
            continue
    japanese = legacy.get("cp932", "")
    if japanese:
        # Full-width hiragana/katakana strongly indicates Japanese.  Do not
        # count half-width katakana here: Chinese GBK decoded as CP932 often
        # turns into a long run of half-width mojibake.
        kana = len(re.findall(r"[\u3040-\u30ff]", japanese))
        han = len(re.findall(r"[\u3400-\u9fff]", japanese))
        if kana >= 2 and kana * 2 >= max(1, han):
            return japanese
    if "gb18030" in legacy:
        return legacy["gb18030"]
    if japanese:
        return japanese
    return data.decode("utf-8", errors="replace")


def load_notes(path: Path) -> dict:
    file = Path(path)
    if not file.is_file():
        return {}
    with file.open("r", encoding="utf-8-sig") as handle:
        payload = json.load(handle)
    if not isinstance(payload, dict):
        raise ValueError("lora_notes.json 顶层必须是 JSON 对象。")
    return payload


def backup_notes(path: Path) -> Path | None:
    file = Path(path)
    if not file.is_file():
        return None
    backup_dir = file.parent / "backup"
    backup_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y-%m-%d_%H%M%S")
    target = backup_dir / f"lora_notes.before-smart-import.{stamp}.json"
    suffix = 1
    while target.exists():
        target = backup_dir / f"lora_notes.before-smart-import.{stamp}.{suffix}.json"
        suffix += 1
    shutil.copy2(file, target)
    return target


def atomic_write_notes(path: Path, notes: dict) -> None:
    file = Path(path)
    file.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=file.name + ".", suffix=".tmp", dir=file.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            json.dump(notes, handle, ensure_ascii=False, indent=2)
            handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, file)
    except Exception:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def _canonical_outfit(outfit: dict) -> dict:
    result = {"name": str(outfit.get("name", "自动识别") or "自动识别").strip()}
    aliases = {"clothing": ("clothing", "prompt"), "other": ("other", "manual")}
    for field in NOTE_FIELDS:
        values = aliases.get(field, (field,))
        value = next((str(outfit.get(key, "") or "").strip() for key in values
                      if str(outfit.get(key, "") or "").strip()), "")
        if value:
            result[field] = ", ".join(_unique(split_prompt_tags(value)))
    return result


def merge_note(existing: dict, parsed: dict, replace: bool = False) -> tuple[dict, bool]:
    """Merge parsed data while preserving non-empty manual fields by default."""
    old = existing if isinstance(existing, dict) else {}
    note = {} if replace else json.loads(json.dumps(old, ensure_ascii=False))
    for field in ("title", "base_model", "weight", "trigger", "url"):
        incoming = str(parsed.get(field, "") or "").strip()
        if incoming and (replace or not str(note.get(field, "") or "").strip()):
            note[field] = incoming
    existing_outfits = [] if replace else [_canonical_outfit(item) for item in note.get("outfits", [])
                                            if isinstance(item, dict)]
    for incoming_raw in parsed.get("outfits", []):
        if not isinstance(incoming_raw, dict):
            continue
        incoming = _canonical_outfit(incoming_raw)
        name_key = normalize_tag(incoming.get("name", ""))
        index = next((i for i, item in enumerate(existing_outfits)
                      if normalize_tag(item.get("name", "")) == name_key), None)
        if index is None:
            existing_outfits.append(incoming)
            continue
        if replace:
            existing_outfits[index] = incoming
            continue
        current = existing_outfits[index]
        for field in NOTE_FIELDS:
            if incoming.get(field) and not current.get(field):
                current[field] = incoming[field]
    if existing_outfits:
        note["outfits"] = existing_outfits
    return note, note != old


