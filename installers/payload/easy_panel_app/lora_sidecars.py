def _unique(values: list[str]) -> list[str]:
    seen: set[str] = set()
    result: list[str] = []
    for value in values:
        item = str(value or "").strip().strip("，,、;；")
        key = normalize_tag(item)
        if item and key and key not in seen:
            seen.add(key)
            result.append(item)
    return result


def split_prompt_tags(value: str, limit: int = 500) -> list[str]:
    """Split tags without breaking weighted parentheses or quoted fragments."""
    text = re.sub(r"<lora:[^>]+>", "", str(value or ""), flags=re.I)
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    result: list[str] = []
    buffer: list[str] = []
    depth = 0
    quote = ""
    for char in text:
        if quote:
            buffer.append(char)
            if char == quote:
                quote = ""
            continue
        if char in {'"', "'"}:
            quote = char
            buffer.append(char)
        elif char in "([{" :
            depth += 1
            buffer.append(char)
        elif char in ")]}" :
            depth = max(0, depth - 1)
            buffer.append(char)
        elif depth == 0 and char in ",，、;；\n":
            item = "".join(buffer).strip().strip("-•* \t")
            if item:
                result.append(item)
            buffer = []
        else:
            buffer.append(char)
    item = "".join(buffer).strip().strip("-•* \t")
    if item:
        result.append(item)
    cleaned: list[str] = []
    for item in result:
        item = re.sub(r"^(?:tags?|prompt)\s*[:：]\s*", "", item, flags=re.I).strip()
        if re.fullmatch(r"https?://\S+", item, re.I):
            continue
        if item:
            cleaned.append(item)
    return _unique(cleaned)[:limit]


def _category_for_header(header: str) -> tuple[str | None, str | None]:
    """Return ``(forced_category, preset_name)`` for a TXT block header."""
    raw = str(header or "").strip().strip("[]【】#：:")
    if "::" in raw:
        preset, category_header = raw.split("::", 1)
        category, _ = _category_for_header(category_header)
        if category:
            return category, preset.strip() or "自动识别"
    low = normalize_tag(raw)
    low = re.sub(r"^tags?\s*\((.*?)\)$", r"\1", low)
    low = re.sub(r"^tags?\s+", "", low)
    for category, aliases in _CATEGORY_ALIASES.items():
        if low in {normalize_tag(alias) for alias in aliases}:
            default_name = "默认服装" if category == "clothing" else None
            return category, default_name

    prefix_patterns = (
        ("subject", r"^(?:角色|人物|character)\s*[-—–]+\s*(.+)$"),
        ("appearance", r"^(?:外貌|appearance)\s*[-—–]+\s*(.+)$"),
        ("clothing", r"^(?:服装|衣服|outfit|costume)\s*[-—–]+\s*(.+)$"),
        ("pose", r"^(?:姿势|动作|pose|action)\s*[-—–]+\s*(.+)$"),
        ("scene", r"^(?:场景|背景|scene|background)\s*[-—–]+\s*(.+)$"),
    )
    for category, pattern in prefix_patterns:
        match = re.match(pattern, raw, re.I)
        if match:
            return category, match.group(1).strip()

    if re.search(r"替代服装|替换服装|alternative outfit", low):
        return "clothing", "替代服装"
    if re.search(r"第二.*服装|second outfit", low):
        return "clothing", "第二套服装"
    if re.search(r"服装触发|default outfit", low):
        return "clothing", "默认服装"
    return None, raw or None


def _meta_label(header: str) -> str | None:
    low = normalize_tag(header)
    for field, aliases in _META_KEYS.items():
        if low in {normalize_tag(alias) for alias in aliases}:
            return field
    return None


def _extract_meta(text: str, filename: str) -> dict[str, str]:
    result = {"title": "", "base_model": "", "weight": "",
              "trigger": "", "url": ""}
    for raw in str(text or "").splitlines():
        line = raw.strip()
        if not line:
            continue
        colon = re.match(r"^([^:：]{1,40})[:：]\s*(.+)$", line)
        if colon:
            field = _meta_label(colon.group(1))
            if field:
                value = colon.group(2).strip()
                if field == "trigger":
                    value = re.split(r"[,，;；]", value, maxsplit=1)[0].strip()
                if field == "url":
                    match = re.search(r"https?://\S+", value)
                    value = match.group(0).rstrip(".,，。") if match else value
                if value and not result[field]:
                    result[field] = value
        if not result["url"]:
            match = re.search(r"https?://\S+", line)
            if match:
                result["url"] = match.group(0).rstrip(".,，。")
        if not result["weight"]:
            match = re.search(
                r"(?:推荐|权重|重量|强度|weight|strength)[^0-9]{0,10}"
                r"([0-9]+(?:\.[0-9]+)?)(?:\s*[-~–—]\s*([0-9]+(?:\.[0-9]+)?))?",
                line, re.I,
            )
            if match:
                result["weight"] = match.group(1) + (("-" + match.group(2)) if match.group(2) else "")
        if not result["trigger"]:
            match = re.search(r"(?:触发词|触发点|trigger(?: word)?)\s*(?:为|[:：])\s*(.+)$", line, re.I)
            if match:
                result["trigger"] = re.split(r"[,，;；。]", match.group(1), maxsplit=1)[0].strip()
        if not result["base_model"]:
            match = re.search(r"(?:适用底模|底模|base model)\s*[:：]\s*([^,，;；。]+)", line, re.I)
            if match:
                result["base_model"] = match.group(1).strip()
    if not result["title"]:
        result["title"] = Path(filename or "LoRA").stem
    return result


def _is_probable_header(line: str) -> bool:
    value = str(line or "").strip()
    if not value or len(value) > 80 or re.search(r"[,，;；]", value):
        return False
    if re.match(r"^(?:%s)" % "|".join(map(re.escape, _SKIP_LINE_PREFIXES)), value, re.I):
        return False
    if _meta_label(value) or _category_for_header(value)[0]:
        return True
    category, _, confidence = classify_tag(value)
    if category != "other" and confidence >= 0.75:
        return False
    if is_trigger_or_character(value):
        return False
    latin_words = re.findall(r"[A-Za-z]+", value)
    cjk = re.findall(r"[\u4e00-\u9fff]", value)
    return bool(cjk) or len(latin_words) <= 6


def _text_blocks(text: str) -> list[tuple[str, list[str]]]:
    blocks: list[tuple[str, list[str]]] = []
    header = "默认预设"
    bracket_context = ""
    lines: list[str] = []

    def flush() -> None:
        nonlocal lines
        if lines:
            blocks.append((header, lines))
        lines = []

    clean_lines = [
        raw.strip().strip("\ufeff")
        for raw in str(text or "").replace("\r\n", "\n").replace("\r", "\n").split("\n")
        if raw.strip().strip("\ufeff") and raw.strip().strip("\ufeff") != SIDECAR_MARKER
    ]

    for index, line in enumerate(clean_lines):
        bracket = re.match(r"^[\[【]([^\]】]{1,60})[\]】]\s*(.*)$", line)
        if bracket:
            flush()
            header = bracket.group(1).strip()
            bracket_context = header
            if bracket.group(2).strip():
                lines.append(bracket.group(2).strip())
            continue
        colon = re.match(r"^([^:：]{1,60})[:：]\s*(.*)$", line)
        if colon:
            label, rest = colon.group(1).strip(), colon.group(2).strip()
            if _meta_label(label):
                if not rest:
                    flush()
                    bracket_context = ""
                    header = label
                continue
            if re.match(r"^(?:%s)" % "|".join(map(re.escape, _SKIP_LINE_PREFIXES)), label, re.I):
                continue
            flush()
            category, _ = _category_for_header(label)
            header = f"{bracket_context}::{label}" if bracket_context and category else label
            if not category:
                bracket_context = ""
            if rest:
                lines.append(rest)
            continue
        compact = re.match(r"^(角色|人物|服装)([^,，]{1,40})[,，]\s*(.+)$", line, re.I)
        if compact:
            flush()
            bracket_context = ""
            header = f"{compact.group(1)} - {compact.group(2).strip()}"
            body = compact.group(3).strip()
            if compact.group(1) in {"角色", "人物"}:
                body = f"{compact.group(2).strip()}, {body}"
            lines.append(body)
            continue
        compact_name = re.match(r"^([\u4e00-\u9fff]{1,12})([A-Z][^,，]{1,40})[,，]\s*(.+)$", line)
        if compact_name:
            flush()
            bracket_context = ""
            header = f"{compact_name.group(1).strip()} {compact_name.group(2).strip()}"
            lines.append(f"{compact_name.group(2).strip()}, {compact_name.group(3).strip()}")
            continue
        mixed = re.match(r"^([\u4e00-\u9fff]{2,16})\s+(.+[,，].+)$", line)
        if mixed:
            flush()
            bracket_context = ""
            header = mixed.group(1).strip()
            lines.append(mixed.group(2).strip())
            continue
        # A lone short line is usually the actual trigger/tag (for example HGK,
        # @artist or a character name), not an empty section title.  Only treat
        # an unlabelled short line as a header when content follows it.
        next_line = clean_lines[index + 1] if index + 1 < len(clean_lines) else ""
        explicit_header = bool(_meta_label(line) or _category_for_header(line)[0])
        next_looks_like_payload = bool(re.search(r"[,，;；]", next_line))
        if (_is_probable_header(line) and next_line
                and (explicit_header or next_looks_like_payload)):
            flush()
            bracket_context = ""
            header = line.rstrip("：:").strip()
            continue
        lines.append(line)
    flush()
    return blocks


def _block_tags(lines: list[str]) -> list[str]:
    tags: list[str] = []
    for line in lines:
        if re.match(r"^(?:%s)" % "|".join(map(re.escape, _SKIP_LINE_PREFIXES)), line, re.I):
            continue
        tags.extend(split_prompt_tags(line))
    return _unique(tags)


def _merge_sections(target: dict[str, list[str]], source: dict[str, list[str]]) -> None:
    for category in NOTE_FIELDS:
        target[category] = _unique(target.get(category, []) + source.get(category, []))


def _serialise_outfit(name: str, sections: dict[str, list[str]]) -> dict:
    result = {"name": str(name or "自动识别").strip() or "自动识别"}
    for category in NOTE_FIELDS:
        values = _unique(sections.get(category, []))
        if values:
            result[category] = ", ".join(values)
    return result


def _folder_hint(filename: str) -> str | None:
    """Use the containing folder only as a fallback for otherwise opaque tags."""
    value = str(filename or "").replace("\\", "/").casefold()
    groups = (
        ("style", ("画风", "风格", "/style", "style/", "styles/", "artist")),
        ("clothing", ("服装", "衣服", "丝袜", "穿搭", "/outfit", "/clothing", "costume")),
        ("subject", ("人物", "角色", "/character", "characters/")),
        ("pose", ("姿势", "动作", "/pose", "poses/")),
        ("scene", ("场景", "背景", "/scene", "background")),
    )
    for category, tokens in groups:
        if any(token in value for token in tokens):
            return category
    return None


def _meta_from_block(meta: dict[str, str], field: str, tags: list[str]) -> list[str]:
    """Consume a bare metadata block and return tags still worth classifying."""
    if not tags:
        return []
    joined = ", ".join(tags).strip()
    if field == "trigger":
        if not meta.get("trigger"):
            meta["trigger"] = tags[0]
        return tags
    if field == "weight":
        match = re.search(r"[0-9]+(?:\.[0-9]+)?(?:\s*[-~–—]\s*[0-9]+(?:\.[0-9]+)?)?", joined)
        if match and not meta.get("weight"):
            meta["weight"] = re.sub(r"\s*[-~–—]\s*", "-", match.group(0))
        return []
    if field == "url":
        match = re.search(r"https?://\S+", joined)
        value = match.group(0).rstrip(".,，。") if match else joined
    else:
        value = joined
    fallback_title = Path(str(meta.get("title", ""))).stem
    source_title = Path(str(meta.get("_source", ""))).stem
    if value and (not meta.get(field) or (field == "title" and fallback_title == source_title)):
        meta[field] = value
    return []


def smart_parse_lora_sidecar(content: str, filename: str = "") -> dict:
    """Parse arbitrary LoRA TXT into canonical, separately stored sections."""
    text = str(content or "")
    meta = _extract_meta(text, filename)
    meta["_source"] = filename
    base_sections = {category: [] for category in NOTE_FIELDS}
    named: list[tuple[str, dict[str, list[str]]]] = []
    unclassified: list[str] = []
    blocks = _text_blocks(text)
    folder_hint = _folder_hint(filename)

    for header, lines in blocks:
        tags = _block_tags(lines)
        if not tags:
            continue
        meta_field = _meta_label(header)
        if meta_field:
            tags = _meta_from_block(meta, meta_field, tags)
            if not tags:
                continue
            header = "默认预设"
        forced, preset_name = _category_for_header(header)
        sections = classify_tag_list(tags)
        sections = {category: list(sections.get(category, [])) for category in NOTE_FIELDS}
        if forced:
            movable = list(sections.get("other", []))
            if movable and forced != "other":
                sections[forced] = _unique(sections.get(forced, []) + movable)
                sections["other"] = []

        # Folder names are useful for opaque activation tokens such as HGK or
        # an artist handle.  They are only allowed to override low-information
        # subject/other results, never a recognised garment, pose, scene, etc.
        populated = {category for category in NOTE_FIELDS if sections.get(category)}
        if not forced and folder_hint and populated and populated <= {"subject", "other"}:
            fallback = _unique(sections.get("subject", []) + sections.get("other", []))
            sections["subject"] = []
            sections["other"] = []
            sections[folder_hint] = fallback

        unclassified.extend(sections.get("other", []))

        generic_header = normalize_tag(header) in {
            "默认预设", "default", "recommended", "推荐", "可选tags", "可选标签",
        }
        if forced and preset_name is None:
            _merge_sections(base_sections, sections)
        elif generic_header:
            _merge_sections(base_sections, sections)
        else:
            name = preset_name or header or "自动识别"
            existing = next((entry for entry in named if normalize_tag(entry[0]) == normalize_tag(name)), None)
            if existing:
                _merge_sections(existing[1], sections)
            else:
                named.append((name, sections))

    outfits: list[dict] = []
    if any(base_sections[category] for category in NOTE_FIELDS):
        if base_sections["subject"] or base_sections["appearance"]:
            base_name = "基础角色"
        elif base_sections["clothing"]:
            base_name = "默认服装"
        else:
            base_name = "自动识别"
        outfits.append(_serialise_outfit(base_name, base_sections))
    outfits.extend(_serialise_outfit(name, sections) for name, sections in named
                   if any(sections[category] for category in NOTE_FIELDS))

    if not meta["trigger"]:
        subject_tags: list[str] = []
        for outfit in outfits:
            subject_tags.extend(split_prompt_tags(outfit.get("subject", "")))
        candidate = next((tag for tag in subject_tags if is_trigger_or_character(tag)), "")
        meta["trigger"] = candidate

    meta.pop("_source", None)
    return {
        "schema_version": 2,
        **meta,
        "outfits": outfits,
        "unclassified": _unique(unclassified),
        "stats": {
            "blocks": len(blocks),
            "presets": len(outfits),
            "classified_tags": sum(
                len(split_prompt_tags(value))
                for outfit in outfits for key, value in outfit.items() if key != "name"
            ),
        },
    }


